import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

const validator = fileURLToPath(new URL("./validate-snapshot.mjs", import.meta.url));
const mock = fileURLToPath(new URL("../data/", import.meta.url));
const { snapshotRoot } = JSON.parse(readFileSync(join(mock, "summary.json"), "utf8"));
const semaPrs = join(snapshotRoot, "modules/clang-sema/prs-index.json");
const astPrs = join(snapshotRoot, "modules/clang-ast/prs-index.json");
const historicalApprovalPr = join(snapshotRoot, "items/pr-101.json");

function run(dir) {
  const result = spawnSync(process.execPath, [validator, dir], { encoding: "utf8" });
  assert.ifError(result.error);
  return result;
}

test("validates the mock snapshot and reports unique cross-module totals", () => {
  const result = run(mock);
  assert.equal(result.status, 0, result.stderr);
  assert.match(result.stdout, /2 modules, 4 unique PRs, 6 unique issues \(2 generated by fuzzer\)/);
});

function copyMock(context) {
  const dir = mkdtempSync(join(tmpdir(), "llvm-prs-snapshot-"));
  context.after(() => rmSync(dir, { recursive: true, force: true }));
  cpSync(mock, dir, { recursive: true });
  return dir;
}

function mutateJson(dir, path, mutate) {
  const target = join(dir, path);
  const json = JSON.parse(readFileSync(target, "utf8"));
  mutate(json);
  writeFileSync(target, JSON.stringify(json));
}

function rejectsMutation(name, path, mutate, error) {
  test(name, (context) => {
    const dir = copyMock(context);
    mutateJson(dir, path, mutate);
    const result = run(dir);
    assert.equal(result.status, 1, result.stdout);
    assert.match(result.stderr, error);
  });
}

rejectsMutation("rejects an index from another snapshot", semaPrs,
  (index) => { index.snapshotId = "mock-other"; }, /shard belongs to another snapshot/);

rejectsMutation("keeps evidence out of index rows", semaPrs,
  (index) => { index.items[0].timeline = []; }, /unevaluated properties/);

rejectsMutation("rejects a stale CI SHA presented as current",
  join(snapshotRoot, "items/pr-101.json"),
  (detail) => { detail.headCi.commitSha = detail.latestApproval.commitSha; },
  /HEAD evidence SHA mismatch/);

rejectsMutation("rejects index drift from the canonical detail", semaPrs,
  (index) => { index.items[0].title = "Stale title"; }, /index and detail disagree/);

rejectsMutation("rejects counting a cross-module fuzzer issue twice", "summary.json",
  (summary) => { summary.kpis.generatedByFuzzer++; }, /global KPIs disagree/);

rejectsMutation("rejects a close candidate whose baseline never reproduced",
  join(snapshotRoot, "items/issue-205.json"),
  (detail) => { detail.conclusion = "close-candidate"; }, /requires a reproducing baseline/);

rejectsMutation("rejects a conclusive fuzzer crash comparison without a signature",
  join(snapshotRoot, "items/issue-203.json"),
  (detail) => { detail.crashSignature = null; }, /conclusive result requires complete evidence/);

rejectsMutation("rejects passing HEAD CI with a failing required check",
  historicalApprovalPr,
  (detail) => { detail.requiredChecks[0].status = "failing"; },
  /passing HEAD CI conflicts with a failing required check/);

test("accepts unknown HEAD CI when required-check coverage is incomplete", (context) => {
  const dir = copyMock(context);
  mutateJson(dir, join(snapshotRoot, "items/pr-103.json"), (detail) => {
    detail.requiredChecks.push({
      name: "clang tests",
      status: "passing",
      commitSha: detail.headSha,
      url: null,
    });
  });
  const result = run(dir);
  assert.equal(result.status, 0, result.stderr);
});

test("reports every orphan in the selected snapshot", (context) => {
  const dir = copyMock(context);
  const items = join(dir, snapshotRoot, "items");
  cpSync(join(items, "pr-101.json"), join(items, "pr-999.json"));
  cpSync(join(items, "issue-201.json"), join(items, "issue-999.json"));
  const result = run(dir);
  assert.equal(result.status, 1, result.stdout);
  assert.match(result.stderr, /unreferenced detail files: issue-999\.json, pr-999\.json/);
});

test("ignores detail files in historical snapshots", (context) => {
  const dir = copyMock(context);
  const history = join(dir, "snapshots/mock-2026-11-26/items");
  mkdirSync(history, { recursive: true });
  writeFileSync(join(history, "pr-999.json"), "{}");
  const result = run(dir);
  assert.equal(result.status, 0, result.stderr);
});

rejectsMutation("rejects zero commit distance for approval on a different SHA",
  historicalApprovalPr,
  (detail) => { detail.commitsSinceApproval = 0; },
  /historical approval requires a positive or unknown commit distance/);

test("accepts unknown commit distance for approval on a different SHA", (context) => {
  const dir = copyMock(context);
  const clearDistance = (item) => { item.commitsSinceApproval = null; };
  mutateJson(dir, historicalApprovalPr, clearDistance);
  for (const index of [semaPrs, astPrs]) {
    mutateJson(dir, index, ({ items }) => clearDistance(items.find((item) => item.id === 101)));
  }
  const result = run(dir);
  assert.equal(result.status, 0, result.stderr);
});

const insufficientIssue = join(snapshotRoot, "items/issue-204.json");

rejectsMutation("rejects claiming that source code is missing when present",
  insufficientIssue,
  (detail) => { detail.missingEvidence.push("source-code"); },
  /missingEvidence must exclude source-code/);

rejectsMutation("rejects omitting a structured reason for evidence that is missing",
  insufficientIssue,
  (detail) => { detail.missingEvidence = detail.missingEvidence.filter((reason) => reason !== "compile-arguments"); },
  /missingEvidence must include compile-arguments/);

test("accepts other evidence gaps and known versions without baseline runs", (context) => {
  const dir = copyMock(context);
  mutateJson(dir, insufficientIssue, (detail) => {
    detail.missingEvidence = detail.missingEvidence.filter((reason) => reason !== "baseline-version");
    detail.missingEvidence.push("other");
  });
  const result = run(dir);
  assert.equal(result.status, 0, result.stderr);
});
