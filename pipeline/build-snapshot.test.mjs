import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { test } from 'node:test'
import { fileURLToPath } from 'node:url'

import { buildSnapshot } from './build-snapshot.mjs'
import { verifyIssue } from './issue-verification.mjs'
import { triagePr } from './pr-triage.mjs'
import { validateSnapshot } from './validate-snapshot.mjs'

const now = '2026-11-27T10:00:00Z'
const url = 'https://llvm.example.invalid'
const snapshotId = 'test-first'
const pr = triagePr(
  {
    id: 9,
    title: 'Cross-module change',
    url: `${url}/pull/9`,
    author: 'author',
    paths: ['clang/lib/Sema/SemaExpr.cpp', 'clang/lib/AST/ASTContext.cpp'],
    headSha: 'f'.repeat(40),
    createdAt: now,
    reviewsComplete: true,
  },
  { now },
)
const issue = verifyIssue({
  id: 9,
  title: 'Fuzzer report',
  url: `${url}/issues/9`,
  moduleIds: pr.moduleIds,
  githubSyncedAt: now,
  originalReportAt: now,
  labels: ['generated by fuzzer'],
  kind: 'crash',
})
const input = { snapshotId, generatedAt: now, prs: [pr, pr], issues: [issue, issue] }

function outputFor(context) {
  const root = mkdtempSync(join(tmpdir(), 'llvm-triage-builder-'))
  context.after(() => rmSync(root, { recursive: true, force: true }))
  return join(root, 'data')
}

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'))
}

test('builds and validates canonical shards and cross-module counts', (context) => {
  const out = outputFor(context)
  const summary = buildSnapshot(input, out)
  assert.deepEqual(readJson(join(out, 'summary.json')), summary)
  assert.equal(summary.kpis.prTotal, 1)
  assert.equal(summary.kpis.issueTotal, 1)
  assert.equal(summary.kpis.generatedByFuzzer, 1)
  assert.equal(summary.kpis.prQueues['awaiting-first-review'], 1)
  assert.equal(summary.kpis.issueConclusions['insufficient-evidence'], 1)
  const root = join(out, summary.snapshotRoot)
  for (const { id, counts } of summary.modules) {
    assert.deepEqual(counts, summary.kpis)
    const index = readJson(join(root, 'modules', id, 'prs-index.json'))
    assert.equal(index.items.length, 1)
    assert.equal(index.items[0].id, 9)
    assert.equal('timeline' in index.items[0], false)
  }
  assert.deepEqual(readJson(join(root, 'items/pr-9.json')).timeline, [])
  assert.equal(readJson(join(root, 'items/issue-9.json')).source, 'generated-by-fuzzer')
  assert.equal(validateSnapshot(out).snapshotId, snapshotId)
})

test('supports retry and keeps published roots available across updates', (context) => {
  const out = outputFor(context)
  const first = buildSnapshot(input, out)
  assert.deepEqual(buildSnapshot(input, out), first)
  const next = buildSnapshot({ ...input, snapshotId: 'test-next', prs: [] }, out)
  assert.equal(validateSnapshot(out).snapshotId, next.snapshotId)
  assert.equal(existsSync(join(out, first.snapshotRoot, 'items/pr-9.json')), true)
  assert.equal(existsSync(join(out, next.snapshotRoot, 'items/pr-9.json')), false)
  assert.throws(
    () => buildSnapshot({ ...input, prs: [] }, out),
    /already exist with different contents/,
  )
  assert.equal(validateSnapshot(out).snapshotId, next.snapshotId)
})

test('rejects invalid staging data before changing the published summary', (context) => {
  const out = outputFor(context)
  buildSnapshot(input, out)
  const invalid = { ...pr, headCi: { ...pr.headCi, commitSha: 'b'.repeat(40) } }
  assert.throws(
    () => buildSnapshot({ ...input, snapshotId: 'invalid', prs: [invalid] }, out),
    /HEAD evidence SHA mismatch/,
  )
  assert.equal(validateSnapshot(out).snapshotId, snapshotId)
  assert.equal(existsSync(join(out, 'snapshots/invalid')), false)
  assert.throws(() => buildSnapshot({ ...input, snapshotId: '../../escape' }, out), /pattern/)
})

test('requires both detail arrays before replacing the published summary', (context) => {
  const out = outputFor(context)
  buildSnapshot(input, out)
  const summary = join(out, 'summary.json')
  const previous = readFileSync(summary)
  for (const field of ['prs', 'issues']) {
    const incomplete = { ...input, snapshotId: 'incomplete' }
    delete incomplete[field]
    assert.throws(() => buildSnapshot(incomplete, out), new RegExp(`explicit ${field} array`))
    assert.throws(
      () => buildSnapshot({ ...incomplete, [field]: null }, out),
      new RegExp(`explicit ${field} array`),
    )
    assert.deepEqual(readFileSync(summary), previous)
    assert.equal(existsSync(join(out, 'snapshots/incomplete')), false)
  }
  assert.equal(
    buildSnapshot({ ...input, snapshotId: 'empty', prs: [], issues: [] }, out).kpis.issueTotal,
    0,
  )
})

test('rejects conflicting details and unconfigured module memberships', (context) => {
  const out = outputFor(context)
  assert.throws(
    () => buildSnapshot({ ...input, prs: [pr, { ...pr, title: 'Drift' }] }, out),
    /Conflicting pr details for ID 9/,
  )
  assert.throws(() => buildSnapshot({ ...input, modules: [] }, out), /unconfigured module/)
  assert.equal(existsSync(out), false)
})

test('builds from a normalized input file through the CLI', (context) => {
  const out = outputFor(context)
  const json = join(out, '..', 'input.json')
  writeFileSync(json, JSON.stringify(input))
  const cli = fileURLToPath(new URL('./build-snapshot.mjs', import.meta.url))
  const result = spawnSync(process.execPath, [cli, json, out], { encoding: 'utf8' })
  assert.ifError(result.error)
  assert.equal(result.status, 0, result.stderr)
  assert.match(result.stdout, /Published validated snapshot test-first/)
  assert.equal(validateSnapshot(out).prTotal, 1)
})
