import assert from 'node:assert/strict'
import { test } from 'node:test'
import { createGitHubCollector } from './github-collector.mjs'
import { normalizeIssue } from './github-normalize.mjs'
import { triagePr } from './pr-triage.mjs'
import { extractReproducer, supportsCompileArgs } from './reproducer.mjs'

const time = '2026-11-27T03:00:00Z'
const old = '2026-11-26T03:00:00Z'
const head = 'a'.repeat(40)
const previous = 'b'.repeat(40)
const human = { login: 'author', type: 'User' }
const reviewer = { login: 'reviewer', type: 'User' }
const bot = { login: 'ci[bot]', type: 'Bot' }
const url = 'https://github.example.invalid/llvm/project'
const source = [
  'Tested on Clang 21.1.0',
  '```cpp',
  'int n;',
  '```',
  "`clang++ -std=c++20 '-DNAME=two words' example.cpp`",
  'error: unexpected diagnostic',
  'Expected behavior: should compile',
].join('\n')

test('extracts a single source, argument tokens and explicitly stated behavior', () => {
  const item = extractReproducer(source)
  assert.equal(item.repro.sourceCode, 'int n;\n')
  assert.deepEqual(item.repro.compileArgs, ['-std=c++20', '-DNAME=two words'])
  assert.equal(item.declaredVersion, '21.1.0')
  assert.deepEqual(item.expectations.expected, { exitCode: 0 })
  assert.equal(supportsCompileArgs(item.repro.compileArgs), true)
  assert.equal(supportsCompileArgs(['-Xclang', 'plugin']), false)
  assert.equal(extractReproducer('clang x.cpp && clang y.cpp').repro.compileArgs, null)
  assert.equal(extractReproducer('clang x.cpp y.cpp').repro.compileArgs, null)
  assert.equal(extractReproducer('Clang 20 and Clang 21').declaredVersion, null)
  assert.equal(extractReproducer('```cpp\nint x;\n```\n```cpp\nint y;\n```').repro.sourceCode, null)
  assert.deepEqual(extractReproducer('clang x.c').repro.compileArgs, [])
})

test('preserves a migrated report date and a stated crash signature', () => {
  const raw = {
    number: 2,
    title: 'Compiler crash',
    html_url: url,
    created_at: old,
    body: 'Originally reported on: 2015-05-02\nAssertion foo failed\n',
    user: human,
    labels: [{ name: 'bugzilla' }, { name: 'clang:frontend' }, { name: 'generated by fuzzer' }],
  }
  const report = normalizeIssue(
    raw,
    [
      { user: human, created_at: old },
      { user: bot, created_at: time },
    ],
    time,
  )
  assert.equal(report.originalReportAt, '2015-05-02T00:00:00.000Z')
  assert.equal(report.originalReportTracker, 'bugzilla')
  assert.equal(report.lastHumanCommentAt, old)
  assert.deepEqual(report.moduleIds, ['clang-sema'])
  assert.equal(report.reportedCrashSignature, 'Assertion foo failed')
  assert.equal(report.repro.sourceCode, null)
})

function githubTransport({ compareStatus = 'ahead', incomplete = false } = {}) {
  const paths = []
  const review = (state, user, sha) => ({
    state,
    user,
    commit_id: sha,
    submitted_at: old,
    html_url: `${url}/review`,
  })
  const pull = {
    number: 1,
    state: 'open',
    title: 'Test',
    created_at: old,
    updated_at: time,
    html_url: url,
    user: human,
    base: { ref: 'main' },
    head: { sha: head },
    labels: [{ name: 'clang:frontend' }],
    mergeable: true,
  }
  const answer = (data, more = false) =>
    Response.json(data, {
      headers: more ? { link: '<https://github.example.invalid/next>; rel="next"' } : {},
    })
  async function fetchImpl(request, options) {
    assert.equal(request.origin, 'https://github.example.invalid')
    assert.equal(options.headers.Authorization, 'Bearer fixture')
    const path = request.pathname.replace('/repos/llvm/project/', '/')
    const page = request.searchParams.get('page')
    paths.push([path, page])
    if (path === '/search/issues') {
      const q = request.searchParams.get('q')
      const number = q.includes('is:merged') ? 3 : q.includes('is:issue') ? 2 : 1
      return answer({ items: [{ number, updated_at: time, labels: pull.labels }] })
    }
    if (path === '/pulls/1') return answer(pull)
    if (/^\/pulls\/[13]\/files$/.test(path)) {
      return page === '1'
        ? answer([{ filename: 'clang/lib/Sema/Decl.cpp' }], true)
        : answer([{ filename: 'clang/lib/AST/Context.cpp' }])
    }
    if (path === '/pulls/1/commits') return answer([])
    if (path === '/pulls/1/reviews')
      return answer(
        [
          review('APPROVED', reviewer, previous),
          review('APPROVED', bot, head),
          review('DISMISSED', { ...reviewer, login: 'dismissed' }, head),
        ],
        incomplete,
      )
    if (path === '/pulls/3/reviews') return answer([review('APPROVED', reviewer, previous)])
    if (path === '/issues/1/timeline') return answer([])
    if (path === '/issues/1/comments')
      return answer([
        { body: 'Could someone merge this for me?', user: human, created_at: time, html_url: url },
      ])
    if (path === '/rules/branches/main')
      return answer([
        {
          type: 'required_status_checks',
          parameters: { required_status_checks: [{ context: 'build' }] },
        },
      ])
    if (path === '/branches/main/protection/required_status_checks') return answer({ contexts: [] })
    if (path.endsWith('/check-runs'))
      return answer({
        check_runs: [
          { head_sha: previous, name: 'build', status: 'completed', conclusion: 'success' },
          { head_sha: head, name: 'build', status: 'completed', conclusion: 'failure' },
        ],
      })
    if (path.endsWith('/statuses')) return answer([])
    if (path === `/compare/${previous}...${head}`)
      return answer({ status: compareStatus, ahead_by: 2 })
    if (path === '/issues/2') return answer({ ...pull, number: 2, body: source })
    if (path === '/issues/2/comments') return answer([])
    assert.fail(`Unexpected GitHub path: ${path}`)
  }
  return { fetchImpl, paths }
}

test('collects paginated observations, exact SHA distances, current checks and reviewer history', async () => {
  const transport = githubTransport()
  const collector = createGitHubCollector({
    repository: 'llvm/project',
    labels: ['clang:frontend'],
    token: 'fixture',
    baseUrl: 'https://github.example.invalid/',
    fetchImpl: transport.fetchImpl,
  })
  const { prs, issues, reviewerHistory } = await collector.collect(time)
  const pr = triagePr(prs[0], { now: time, reviewerHistory })
  assert.deepEqual(pr.moduleIds, ['clang-sema', 'clang-ast'])
  assert.equal(pr.commitsSinceApproval, 2)
  assert.equal(pr.headCi.status, 'failing')
  assert.notEqual(pr.headReview.status, 'approved')
  assert.equal(pr.mergeHelpRequested, true)
  assert.equal(pr.suggestedReviewers[0].login, reviewer.login)
  assert.ok(transport.paths.some(([path, page]) => path === '/pulls/1/files' && page === '2'))
  assert.equal(issues[0].declaredVersion, '21.1.0')
})

test('keeps force-push distances and incomplete review observations unknown', async () => {
  const { fetchImpl } = githubTransport({ compareStatus: 'diverged', incomplete: true })
  const collector = createGitHubCollector({
    repository: 'llvm/project',
    labels: ['clang:frontend'],
    token: 'fixture',
    baseUrl: 'https://github.example.invalid/',
    fetchImpl,
    maxPages: 1,
    maxHistory: 0,
  })
  const { prs } = await collector.collect(time)
  const pr = triagePr(prs[0], { now: time })
  assert.equal(pr.commitsSinceApproval, null)
  assert.equal(pr.headReview.status, 'unknown')
})

test('times out even when the injected transport does not settle', async () => {
  const collector = createGitHubCollector({ timeoutMs: 5, fetchImpl: () => new Promise(() => {}) })
  await assert.rejects(collector.collect(time), /timed out/)
})
