import assert from "node:assert/strict";
import { test } from "node:test";

import { extractCrashSignature, issueSource, matchRun, verifyIssue } from "./issue-verification.mjs";

const old = "2012-01-01T00:00:00Z";
const now = "2026-11-27T00:00:00Z";
const assertion = "Sema assertion 'result.isValid()' failed.";
const diagnostic = "example.cpp:2:5: error: unexpected diagnostic\n    ^";
const run = (outcome, diagnostics = diagnostic, exitCode = 1) => ({
  compilerId: "clang-test", compilerVersion: "clang test",
  exitCode, diagnostics, godboltUrl: null, outcome,
});

function issue({ runs, ...options } = {}) {
  return verifyIssue({
    id: 10, title: "Unexpected diagnostic", url: "https://llvm.example.invalid/issues/10",
    moduleIds: ["clang-sema"], originalReportAt: old, lastHumanCommentAt: old,
    githubSyncedAt: now, lastVerifiedAt: now, reporterIsBot: false, kind: "diagnostic",
    repro: { sourceCode: "int x;", compileArgs: [], expectedBehavior: "Accepts the source" },
    runs,
    ...options,
  });
}

test("source and verification conclusion are independent", () => {
  assert.equal(issueSource({ reporterIsBot: false, labels: ["Generated by fuzzer"] }), "generated-by-fuzzer");
  assert.equal(issueSource({ reporterIsBot: false }), "human-reported");
  assert.equal(issueSource({ reporterIsBot: true }), "unknown");
  assert.equal(issueSource({ labels: ["unrelated"] }), "unknown");
  const base = run("reported-symptom", assertion, 134);
  const options = { labels: ["generated-by-fuzzer"], kind: "crash" };
  const still = issue({ ...options, runs: { baseline: base, trunk: base } });
  const passed = issue({ ...options, runs: { baseline: base, trunk: run("expected-behavior", "", 0) } });
  assert.equal(still.source, passed.source);
  assert.equal(still.conclusion, "still-reproducible");
  assert.equal(passed.conclusion, "close-candidate");
  assert.equal(still.lastHumanCommentAt, old);
  assert.equal(passed.crashSignature, assertion);
});

test("an unverified baseline cannot support a close candidate", () => {
  const passing = run("expected-behavior", "", 0);
  const detail = issue({ runs: { baseline: passing, trunk: passing } });
  assert.equal(detail.conclusion, "insufficient-evidence");
  assert.deepEqual(detail.missingEvidence, ["baseline-symptom"]);
});

test("generates evidence gaps without claiming that present input is missing", () => {
  const detail = issue({
    labels: ["generated-by-fuzzer"], kind: "crash", baselineVersionKnown: false,
    repro: { sourceCode: "int x;", compileArgs: null }, otherEvidenceMissing: true,
    runs: { baseline: null, trunk: run("different-behavior") },
  });
  assert.deepEqual(detail.missingEvidence, [
    "compile-arguments", "expected-behavior", "baseline-run", "trunk-outcome",
    "crash-signature", "baseline-version", "other",
  ]);
  assert.equal(detail.crashSignature, null);
});

test("requires a crash signature for conclusive fuzzer crash comparisons", () => {
  const base = run("reported-symptom", "No identifiable signature", 134);
  const detail = issue({
    labels: ["generated-by-fuzzer"], kind: "crash",
    runs: { baseline: base, trunk: run("expected-behavior", "", 0) },
  });
  assert.deepEqual(detail.missingEvidence, ["crash-signature"]);
  assert.equal(detail.conclusion, "insufficient-evidence");
  assert.equal(extractCrashSignature("PLEASE submit a bug report\n " + assertion), assertion);
});

test("retains a human-reported crash signature without requiring it for a conclusion", () => {
  const runs = { baseline: run("reported-symptom", assertion, 134),
    trunk: run("expected-behavior", "", 0) };
  const detail = issue({ kind: "crash", reportedCrashSignature: assertion, runs });
  assert.equal(detail.source, "human-reported");
  assert.equal(detail.crashSignature, assertion);
  assert.equal(detail.conclusion, "close-candidate");
  const withoutSignature = issue({ kind: "crash", runs });
  assert.equal(withoutSignature.crashSignature, null);
  assert.deepEqual(withoutSignature.missingEvidence, []);
  assert.equal(withoutSignature.conclusion, "close-candidate");
});

test("keeps fix attribution independent of the version comparison", () => {
  const fixAttribution = {
    status: "candidate", commitSha: "a".repeat(40),
    reason: "Related change", evidenceUrls: ["https://llvm.example.invalid/commit/mock"],
  };
  const runs = { baseline: run("reported-symptom"), trunk: run("expected-behavior", "", 0) };
  assert.equal(issue({ runs }).fixStatus, "unknown");
  assert.deepEqual(issue({ runs, fixAttribution }).fixAttribution, fixAttribution);
  assert.equal(issue({ fixAttribution }).conclusion, "insufficient-evidence");
  assert.deepEqual(issue({ runs, lastVerifiedAt: null }).missingEvidence, ["other"]);
});

test("matches run outcomes using diagnostic evidence and explicit expected behavior", () => {
  const outcome = (exitCode, diagnostics, expectations) => matchRun({ exitCode, diagnostics }, expectations);
  const expected = { exitCode: 1, diagnosticIncludes: "expected diagnostic:" };
  const reported = { exitCode: 1, diagnosticIncludes: "unexpected diagnostic" };
  assert.equal(outcome(1, diagnostic, { reported, expected }), "reported-symptom");
  assert.equal(outcome(1, "expected diagnostic: details", { reported, expected }), "expected-behavior");
  assert.equal(outcome(1, "unknown argument", { reported, expected }), "different-behavior");
  assert.equal(outcome(1, "", { reported: { exitCode: 1 } }), "unknown");
  assert.equal(outcome(1, diagnostic, { reported, expected: { exitCode: 1 } }), "unknown");
  assert.equal(outcome(134, assertion, { expected: { exitCode: 134 } }), "unknown");
});
